// Writes the browser copy of the well-known-bots seed that Cloud uses to
// classify user agents. Run from frontend/: node scripts/generate-well-known-bots.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const seedPath = path.join(root, "..", "backend", "utils", "well_known_bots_seed.json");
const outPath = path.join(root, "lib", "cloud-engine", "bots", "well-known-bots.generated.ts");

// Ports of extract_literal_substring and extract_entry_referral_stems in
// backend/utils/bot_sources/registry.py; tests/utils/test_well_known_bots_browser_copy.py
// fails when the output differs from the Python helpers.
const LITERAL_ESCAPES = new Set("\\/.,-_+:; ");
const BOT_TOKEN_SUFFIX_RE =
  /(-searchbot|-assistbot|-externalagent|-externalfetcher|-extended|-user|searchbot|assistbot|externalagent|externalfetcher|extended|crawler|spider|slurp|archiver|scraper|preview|other|bot).*$/i;
const DOMAIN_STEM_RE = /^(?:https?:\/\/)?(?:www\.)?([^/.:;\s]+)/i;
const DOMAIN_NOISE = new Set(["com", "org", "net", "io", "ai", "co", "uk", "ru", "cn", "de", "jp", "fr", "crawl", "search", "bot", "spider"]);

function stripChars(s, chars) {
  let start = 0;
  let end = s.length;
  while (start < end && chars.includes(s[start])) start++;
  while (end > start && chars.includes(s[end - 1])) end--;
  return s.slice(start, end);
}

function extractLiteralSubstring(pattern) {
  let best = "";
  let current = [];
  const commit = () => {
    const s = current.join("").trim();
    if (s.length > best.length) best = s;
    current = [];
  };
  let i = 0;
  const n = pattern.length;
  while (i < n) {
    const c = pattern[i];
    if (c === "\\" && i + 1 < n) {
      if (LITERAL_ESCAPES.has(pattern[i + 1])) current.push(pattern[i + 1]);
      else commit();
      i += 2;
    } else if (c === "[") {
      commit();
      let depth = 1;
      i += 1;
      while (i < n && depth > 0) {
        if (pattern[i] === "]") depth -= 1;
        else if (pattern[i] === "[") depth += 1;
        i += 1;
      }
    } else if ("(){}*+?^$|".includes(c)) {
      commit();
      i += 1;
    } else {
      current.push(c);
      i += 1;
    }
  }
  commit();
  return best.length >= 4 ? best : null;
}

function tokenStem(text) {
  const tok = stripChars(text.split("/")[0].split("\\")[0], "^$()[]{}+*?.,; ").toLowerCase();
  return stripChars(tok.replace(BOT_TOKEN_SUFFIX_RE, ""), "-_.");
}

export function referralStems(entry) {
  const stems = new Set();
  const botId = (entry.id ?? "").toLowerCase();
  if (botId) {
    const vendor = botId.split("-")[0];
    if (vendor.length >= 3) stems.add(vendor);
  }
  const m = DOMAIN_STEM_RE.exec(entry.url ?? "");
  if (m && m[1].length >= 3) stems.add(m[1].toLowerCase());
  for (const dom of entry.verification?.domains ?? []) {
    for (const part of stripChars(dom.toLowerCase(), ".").split(".")) {
      if (part && !DOMAIN_NOISE.has(part) && part.length >= 3) stems.add(part);
    }
  }
  for (const pat of entry.pattern?.accepted ?? []) {
    const stem = tokenStem(extractLiteralSubstring(pat) ?? pat);
    if (stem.length >= 3) stems.add(stem);
  }
  for (const pat of entry.instances?.accepted ?? []) {
    const stem = tokenStem(pat);
    if (stem.length >= 3) stems.add(stem);
  }
  // Code-point order, like Python's sorted().
  return [...stems].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

export function slimWellKnownBots(seed) {
  return seed.map((entry) => [
    entry.id ?? "unknown",
    entry.categories?.[0] ?? "unknown",
    entry.pattern?.accepted ?? [],
    referralStems(entry),
    entry.verification?.domains ?? [],
    entry.aliases ?? [],
  ]);
}

export function renderWellKnownBotsModule(seed) {
  const lines = slimWellKnownBots(seed).map((row) => `  ${JSON.stringify(row)},`);
  return [
    "// Generated by scripts/generate-well-known-bots.mjs from",
    "// backend/utils/well_known_bots_seed.json. Do not edit by hand.",
    "export const WELL_KNOWN_BOTS: readonly (readonly [",
    "  id: string,",
    "  category: string,",
    "  patterns: readonly string[],",
    "  referralStems: readonly string[],",
    "  verificationDomains: readonly string[],",
    "  aliases: readonly string[],",
    "])[] = [",
    ...lines,
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const seed = JSON.parse(readFileSync(seedPath, "utf8"));
  writeFileSync(outPath, renderWellKnownBotsModule(seed));
}
