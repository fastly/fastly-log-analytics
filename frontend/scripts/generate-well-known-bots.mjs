// Writes the browser copy of the well-known-bots seed that Cloud uses to
// classify user agents. Run from frontend/: node scripts/generate-well-known-bots.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const seedPath = path.join(root, "..", "backend", "utils", "well_known_bots_seed.json");
const outPath = path.join(root, "lib", "cloud-engine", "bots", "well-known-bots.generated.ts");

export function slimWellKnownBots(seed) {
  return seed.map((entry) => [
    entry.id ?? "unknown",
    entry.categories?.[0] ?? "unknown",
    entry.pattern?.accepted ?? [],
  ]);
}

export function renderWellKnownBotsModule(seed) {
  const lines = slimWellKnownBots(seed).map((row) => `  ${JSON.stringify(row)},`);
  return [
    "// Generated by scripts/generate-well-known-bots.mjs from",
    "// backend/utils/well_known_bots_seed.json. Do not edit by hand.",
    "export const WELL_KNOWN_BOTS: readonly (readonly [id: string, category: string, patterns: readonly string[]])[] = [",
    ...lines,
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const seed = JSON.parse(readFileSync(seedPath, "utf8"));
  writeFileSync(outPath, renderWellKnownBotsModule(seed));
}
