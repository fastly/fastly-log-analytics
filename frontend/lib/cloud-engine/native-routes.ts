export function isNativeCloudRoute(method: string, pathname: string): boolean {
  return NATIVE_ROUTES.some(([methods, template]) =>
    methods.split(",").includes(method.toUpperCase()) &&
    new RegExp(`^${template.replace(/\{[^}]+\}/g, "[^/]+")}$`).test(pathname),
  );
}
